// Seed initializes the standard policy rules and policy packs into the store.
// The operation is strictly idempotent and safe to run on every gateway startup.
func Seed(ctx context.Context, store Store) error {
	if store == nil {
		return errors.New("policy store is nil")
	}

	// 1. Seed rules
	for _, rule := range builtinRules() {
		existing, err := store.GetRule(ctx, rule.ID)
		if err != nil && !errors.Is(err, ErrRuleNotFound) {
			return fmt.Errorf("check rule %s: %w", rule.ID, err)
		}
		if existing == nil {
			r := rule
			if err := store.CreateRule(ctx, &r); err != nil {
				return fmt.Errorf("seed rule %s: %w", rule.ID, err)
			}
		}
	}

	// 2. Seed packs
	for _, pack := range BuiltinPacks() {
		existing, err := store.GetPack(ctx, pack.ID)
		if err != nil && !errors.Is(err, ErrPackNotFound) {
			return fmt.Errorf("check pack %s: %w", pack.ID, err)
		}
		if existing == nil {
			p := pack
			if err := store.CreatePack(ctx, &p); err != nil {
				return fmt.Errorf("seed pack %s: %w", pack.ID, err)
			}
		}
	}

	return nil
}
